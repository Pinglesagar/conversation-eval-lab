"""Regenerate the committed audio fixtures. Needs a real TTS engine; run on demand.

WHAT THIS DEMONSTRATES
----------------------
How a repository can ship a *real* audio pipeline that a reviewer can run in two
seconds with no models, no network and no API keys — by separating the thing that
needs a synthesiser (recording) from the thing that does not (replay), and by
committing the recording.

The generator runs in three passes, and the order is the whole trick.

    Pass A  discover the dialogue.
            Real TTS, real perturbations, a stand-in for the missing STT. The
            conversation is driven to completion so we learn every line that has
            to be synthesised — which cannot be known in advance, because the
            caller's later lines depend on the agent's replies.

    Pass B  record the clips, then the transcripts.
            Every discovered line is synthesised once and written as 16 kHz mono
            Ogg Opus, indexed in a manifest. Then each scenario is re-run reading
            those clips, so the transcript cassette is keyed by the digest of the
            audio *as it will be replayed* — after the Opus round trip, after the
            perturbation chain.

    Pass C  record the traces.
            Each scenario runs one final time from the committed clips and the
            committed cassette. The traces written here are therefore replay
            traces, which is what makes `tests/test_audio_replay.py` able to
            assert exact equality rather than "close enough": re-running the
            replay must reproduce the committed bytes.

Recording the fixture with the same code path that consumes it is the only way
the fixture proves anything. A fixture generated by a privileged path — one that
knew the answer, or timed things differently, or skipped the encoder — would be a
fixture whose green test says nothing about the code a real run executes.

WHY THE STT IS A STAND-IN HERE, AND WHAT THAT COSTS
---------------------------------------------------
No speech-recognition engine is committed and none is downloaded at test time, so
by default this generator transcribes with `ReferenceSTT`: it returns the line
that was just synthesised, and labels the result `provenance="reference"`. That
label travels into the cassette and into every committed trace, and
`lab.voice.adapter.audio_wer_report` refuses to compute a word error rate from it.

That refusal is correct and it is not a formality. A reference transcript is the
ground truth, so WER against it is exactly 0.0% — on the clean rows and on the
6 dB-SNR-down-a-telephone-line row alike. Shipping that number would be
publishing a fabricated finding, and a flattering one.

Install whisper.cpp with `scripts/setup_audio.sh` and re-run with `--stt whisper`
and the cassette records real transcripts with `provenance="recorded"`, the traces
say so, and the same `audio_wer_report` call starts answering with a real figure.

WHAT GETS COMMITTED, AND THE ARITHMETIC
---------------------------------------
Caller audio for every voice scenario, and agent audio for one showcase scenario.
That asymmetry is deliberate and it is a size decision made in the open:

*   Caller clips are what the perturbation chain, the digests and the STT leg all
    operate on, so every scenario needs them to replay at all. They are short —
    the corpus's caller lines are brief by design — so all of them fit easily.
*   Agent replies are several times longer in total, and their only unique
    contribution is `agent_audio_complete`, hence real speaking time. One
    scenario's worth proves the events and the arithmetic; eight would multiply
    the committed bytes for a metric that is already demonstrated.

Every scenario therefore gets latency (the calibrated figure), the perturbation
descriptors and the STT leg; one gets speaking time as well. The generator prints
the measured Opus and equivalent-WAV totals so the trade is a number and not a
claim, and `fixtures/audio/audio_fixtures.md` records them.

USAGE
-----
    make audio-fixtures                       # macOS `say`, the zero-download path
    python -m scripts.make_audio_fixtures --engine kokoro
    python -m scripts.make_audio_fixtures --stt whisper --engine kokoro
    python -m scripts.make_audio_fixtures --check     # verify, write nothing
"""

