def build_caller(scenario: Scenario, corpus: Corpus) -> ScriptedCaller:
    """A deterministic caller for a voice row, scripted from its reference transcript.

    `voice.reference_transcript` is the lines the caller actually speaks — it is
    already the ground truth for word error rate, which makes it the same thing a
    script is. Reusing it rather than adding a second `script:` field keeps one
    statement of what the caller said, so the audio and the WER reference cannot
    drift apart.

    Note what this inherits: the reference transcript is a *partial* script, so
    several voice rows run out of lines while the agent is still asking questions
    and the caller hangs up. That is the corpus's shape, not a bug here, and the
    resulting traces are short. They are still complete audio sessions, which is
    what these fixtures are for.
    """
    if scenario.voice is None or not scenario.voice.reference_transcript:
        raise ValueError(
            f"{scenario.id} declares no reference_transcript, so there is no caller "
            "script to synthesise; add one to the voice block"
        )
    return ScriptedCaller(
        scenario.voice.reference_transcript,
        profile=scenario.caller_profile(corpus.personas),
    )


def voice_scenarios(corpus: Corpus) -> list[Scenario]:
    return [s for s in corpus.scenarios if s.suite == "voice"]


def _engine(name: str) -> Any:
    if name == "say":
        return SystemSayTTS()
    if name == "kokoro":
        return KokoroTTS()
    raise SystemExit(f"unknown --engine {name!r}; choose 'say' or 'kokoro'")


