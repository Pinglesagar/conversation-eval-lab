class RecordingTTS:
    """Wraps a real TTS engine and remembers every line it was asked to speak.

    Pass A needs to learn the dialogue, and the dialogue is not knowable in
    advance: the caller's third line depends on the agent's second reply, which
    depends on what the agent heard. Driving the conversation with a recording
    wrapper is how the set of lines to synthesise gets discovered rather than
    guessed — and a guessed list is how a fixture set ends up missing exactly the
    line a scenario needs.
    """

    def __init__(self, inner: Any, *, role: str) -> None:
        self.inner = inner
        self.role = role
        self.name = inner.name
        self.is_replay = getattr(inner, "is_replay", False)
        self.spoken: list[str] = []
        self.last: SynthesisResult | None = None

    def available(self) -> bool:
        return self.inner.available()

    def describe(self) -> str:
        return f"recording({self.role}) over {self.inner.describe()}"

    def synthesise(
        self, text: str, *, sample_rate: int = DEFAULT_SAMPLE_RATE, voice: str | None = None
    ) -> SynthesisResult:
        result = self.inner.synthesise(text, sample_rate=sample_rate, voice=voice)
        self.spoken.append(text)
        self.last = result
        return result


class ReferenceSTT:
    """Returns the line that was just synthesised, and says that is what it did.

    Not a speech engine, and shaped so that nothing can mistake it for one: it
    reports `provenance="reference"` and an engine identity of `reference-text`,
    which is the value `lab.voice.adapter.audio_wer_report` refuses on.

    It reads the caller's line from the recording TTS rather than from the
    samples, which is exactly the back-channel a real engine cannot have — and
    the reason this class lives in a generator script instead of in `lab`. The
    library's honest offline path is `FixtureTTS` plus `RecordedSTT`: replay
    something a real engine produced, or refuse.
    """

    def __init__(self, source: RecordingTTS) -> None:
        self.source = source
        self.name = f"{REFERENCE_ENGINE}(stand-in)"
        self.is_replay = False

    def available(self) -> bool:
        return True

    def describe(self) -> str:
        return f"{self.name}: returns the synthesised line; not a speech engine"

    def transcribe(
        self, audio: Audio, *, sample_rate: int = DEFAULT_SAMPLE_RATE
    ) -> Transcription:
        last = self.source.last
        if last is None:  # pragma: no cover - the adapter always synthesises first
            raise RuntimeError("ReferenceSTT was asked to transcribe before any synthesis")
        return Transcription(
            text=last.text, engine=REFERENCE_ENGINE, provenance="reference", language="en"
        )


