def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m scripts.make_audio_fixtures",
        description="Regenerate the committed audio fixtures from real speech.",
    )
    parser.add_argument(
        "--engine",
        default="say" if platform.system() == "Darwin" else "kokoro",
        choices=("say", "kokoro"),
        help="Synthesiser. 'say' is macOS-only and needs no download; "
        "'kokoro' is local, Apache-2.0, and needs scripts/setup_audio.sh.",
    )
    parser.add_argument(
        "--stt",
        default="reference",
        choices=("reference", "whisper"),
        help="'reference' records the ground truth as a stand-in and the harness "
        "then refuses to report WER. 'whisper' records real transcripts.",
    )
    parser.add_argument("--out", default=str(FIXTURE_ROOT), help="Fixture directory.")
    parser.add_argument("--showcase", default=SHOWCASE_SCENARIO, help="Scenario to record agent audio for.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Replay the committed fixtures and report whether they still match; write nothing.",
    )
    return parser


def _check(root: Path, scenarios: Sequence[Scenario], corpus: Corpus, showcase: str) -> int:
    """Replay and diff against the committed traces. Exits non-zero on drift."""
    from lab.trace.io import read_jsonl  # noqa: PLC0415 - only the check path needs it

    produced = record_traces(scenarios, corpus, root=root, showcase=showcase, write=False)
    drift: list[str] = []
    for scenario_id, trace in produced.items():
        path = root / "traces" / f"{scenario_id}.jsonl"
        if not path.is_file():
            drift.append(f"{scenario_id}: no committed trace at {path}")
            continue
        committed = read_jsonl(path)
        if committed.model_dump() != trace.model_dump():
            drift.append(f"{scenario_id}: replay does not match {path}")
    print(f"checked {len(produced)}/{len(scenarios)} scenario(s) against {root}")
    for line in drift:
        print(f"  DRIFT  {line}")
    print("verdict:", "PASS" if not drift else f"FAIL ({len(drift)} drifted)")
    return 0 if not drift else 1


def main(argv: Sequence[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    root = Path(args.out)
    corpus = load_corpus()
    scenarios = voice_scenarios(corpus)
    if not scenarios:
        print("no voice scenarios found; nothing to record", file=sys.stderr)
        return 1
    rates = {s.voice.sample_rate for s in scenarios if s.voice is not None}
    if len(rates) != 1:
        print(
            f"voice scenarios declare {len(rates)} different sample rates {sorted(rates)}; "
            "one fixture directory holds one rate, so record them separately",
            file=sys.stderr,
        )
        return 1
    sample_rate = rates.pop()

    if args.check:
        return _check(root, scenarios, corpus, args.showcase)

    tts = _engine(args.engine)
    if not tts.available():
        print(f"{tts.describe()} is not available on this machine.", file=sys.stderr)
        print("Run scripts/setup_audio.sh, or use --engine say on a Mac.", file=sys.stderr)
        return 1
    stt_engine = None
    if args.stt == "whisper":
        whisper = WhisperCppSTT()
        if not whisper.available():
            print(f"{whisper.describe()} is not available.", file=sys.stderr)
            print("Run scripts/setup_audio.sh to build whisper.cpp and fetch a model.", file=sys.stderr)
            return 1
        stt_engine = whisper

    print(f"recording {len(scenarios)} voice scenario(s) at {sample_rate} Hz")
    print(f"  synthesiser : {tts.describe()}")
    print(f"  transcriber : {stt_engine.describe() if stt_engine else 'reference stand-in (WER will be refused)'}")

    print("pass A: discovering the dialogue")
    caller_lines, agent_lines = discover_lines(
        scenarios, corpus, tts=tts, showcase=args.showcase
    )
    print(f"  {len(caller_lines)} caller line(s), {len(agent_lines)} agent line(s)")

    print("pass B: recording clips")
    manifest = record_clips(
        caller_lines, agent_lines, tts=tts, root=root, sample_rate=sample_rate
    )
    opus, wav, samples, ratio = _size_table(manifest)
    print(
        f"  {len(manifest['clips'])} clip(s), {samples / sample_rate:.1f} s of speech: "
        f"{opus / 1024:.1f} KiB Opus vs {wav / 1024:.1f} KiB WAV ({ratio:.1f}x)"
    )
    print(
        f"  {manifest['clips_unchanged']}/{len(manifest['clips'])} clip(s) already matched "
        "and were left untouched (an Ogg re-encode changes the bytes, not the audio)"
    )

    print("pass B: recording transcripts")
    cassette = record_cassette(
        scenarios, corpus, root=root, showcase=args.showcase, stt_engine=stt_engine
    )
    print(f"  {len(cassette['entries'])} transcript(s)")

    print("pass C: recording traces")
    traces = record_traces(scenarios, corpus, root=root, showcase=args.showcase)
    for scenario_id, trace in traces.items():
        print(f"  {scenario_id}: {len(trace)} events, {trace.duration():.2f} s")

    readme = write_readme(
        root,
        manifest=manifest,
        cassette=cassette,
        traces=traces,
        showcase=args.showcase,
        sample_rate=sample_rate,
    )
    print(f"wrote {readme}")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    raise SystemExit(main())
