def clip_is_unchanged(path: Path, audio: Audio, sample_rate: int) -> bool:
    """True when encoding `audio` would reproduce the clip already at `path`.

    Precisely: encode `audio` to a temporary file, decode it, decode `path`, and
    compare the two digests. Note the direction — this asks whether *these
    samples* produce the committed clip, so passing a decode of `path` back in
    returns False. Opus is lossy and a second pass through it loses more; the
    generator only ever hands this a fresh synthesis, which is the case it is for.

    WHY THIS FUNCTION EXISTS
    ------------------------
    An Ogg bitstream carries a randomly chosen stream serial number, so encoding
    the same samples twice produces two files with identical decoded audio and
    different bytes. Left alone, `make audio-fixtures` would therefore rewrite
    every clip on every run, and each run would add ~300 KiB of new blobs to git
    history for no change in the audio at all.

    So the comparison is made where it means something: encode the candidate to a
    temporary file, decode it, decode the committed clip, and compare the two
    digests. Equal digests mean the committed clip already *is* this audio and is
    left exactly as it is.

    This is the difference between a generator that is idempotent and one that
    merely looks it. The traces, the manifest and the cassette were already
    reproducible — they are derived from decoded audio, which is stable — and this
    makes the committed binaries reproducible too.
    """
    if not path.is_file():
        return False
    try:
        existing, existing_rate = read_audio(path)
    except Exception:
        return False
    if existing_rate != sample_rate:
        return False
    with tempfile.TemporaryDirectory(prefix="lab-clip-compare-") as directory:
        candidate = Path(directory) / f"candidate{CLIP_SUFFIX}"
        write_audio(candidate, audio, sample_rate)
        encoded, encoded_rate = read_audio(candidate)
    return encoded_rate == existing_rate and audio_digest(
        encoded, encoded_rate
    ) == audio_digest(existing, existing_rate)


def record_clips(
    caller_lines: Sequence[str],
    agent_lines: Sequence[str],
    *,
    tts: Any,
    root: Path,
    sample_rate: int,
) -> dict[str, Any]:
    """Synthesise each line once, write it as Ogg Opus, and build the manifest.

    A clip whose committed bytes already decode to this audio is left untouched
    (see `clip_is_unchanged`), and clips the new manifest does not reference are
    pruned at the end rather than deleted up front — so a failure part-way through
    leaves the previous fixture set intact instead of half of it.
    """
    clips_dir = root / "clips"
    clips_dir.mkdir(parents=True, exist_ok=True)

    manifest: dict[str, Any] = {
        "generated_by": "scripts/make_audio_fixtures.py",
        "engine": tts.name,
        "voice": getattr(tts, "voice", None),
        "sample_rate": sample_rate,
        "format": "16 kHz mono Ogg Opus",
        "clips": {},
    }
    kept = 0
    for role, lines in (("caller", caller_lines), ("agent", agent_lines)):
        for line in lines:
            result = tts.synthesise(line, sample_rate=sample_rate)
            key = text_digest(line, sample_rate)
            filename = f"{role}-{key[:12]}{CLIP_SUFFIX}"
            path = clips_dir / filename
            if clip_is_unchanged(path, result.audio, sample_rate):
                kept += 1
            else:
                write_audio(path, result.audio, sample_rate)
            decoded, _rate = read_audio(path)
            manifest["clips"][key] = {
                "file": f"clips/{filename}",
                "role": role,
                "text": line,
                "voice": result.voice,
                "sample_rate": sample_rate,
                # Taken from the *decoded* clip, because the decoded clip is what
                # every replay reads. A count from the pre-encode synthesis would
                # be a claim about audio no test ever sees.
                "samples": int(decoded.size),
                "duration_s": round(decoded.size / sample_rate, 4),
                "bytes": path.stat().st_size,
                "pcm16_bytes": int(decoded.size) * 2,
            }
    referenced = {Path(entry["file"]).name for entry in manifest["clips"].values()}
    for stale in sorted(clips_dir.glob(f"*{CLIP_SUFFIX}")):
        if stale.name not in referenced:
            stale.unlink()
    manifest["clips_unchanged"] = kept
    (root / ClipManifest.FILENAME).write_text(
        json.dumps(manifest, indent=2, sort_keys=False) + "\n", encoding="utf-8"
    )
    return manifest


def record_cassette(
    scenarios: Sequence[Scenario],
    corpus: Corpus,
    *,
    root: Path,
    showcase: str,
    stt_engine: Any | None,
) -> dict[str, Any]:
    """Re-run from the committed clips and record a transcript per perturbed clip.

    The digest is taken from the audio the replay path actually produces — after
    the Opus round trip and after the perturbation chain — which is why this pass
    cannot be merged into the one that wrote the clips. A cassette keyed by
    pre-encoding audio would miss on every lookup, and a cassette keyed by the
    line of dialogue would hit even when the audio had changed underneath it.
    """
    fixture_tts = FixtureTTS(root)
    entries: dict[str, dict[str, Any]] = {}
    for scenario in scenarios:
        assert scenario.voice is not None
        recorder = RecordingTTS(fixture_tts, role="caller")
        stt = stt_engine if stt_engine is not None else ReferenceSTT(recorder)
        clock = FakeClock()
        adapter = AudioAdapter(
            tts=recorder,
            stt=stt,
            agent_tts=fixture_tts,
            sample_rate=scenario.voice.sample_rate,
            perturbations=scenario.voice.chain(),
            gate=LatencyGate.skipped(),
            synthesise_agent_audio=scenario.id == showcase,
        )
        adapter.run(
            scenario_id=scenario.id,
            agent=build_agent(clock=clock),
            caller=build_caller(scenario, corpus),
            clock=clock,
        )
        for turn in adapter.turns:
            entries[turn.caller_digest] = {
                "text": turn.heard_text,
                "engine": getattr(stt, "name", REFERENCE_ENGINE)
                if stt_engine is not None
                else REFERENCE_ENGINE,
                "provenance": turn.provenance,
                "language": "en",
                "spoken": turn.caller_text,
                "scenario": scenario.id,
            }
    cassette = {
        "generated_by": "scripts/make_audio_fixtures.py",
        "keyed_by": "sha256 of the perturbed clip as 16-bit PCM, per lab.voice.engines.base.audio_digest",
        "entries": entries,
    }
    (root / TranscriptCassette.FILENAME).write_text(
        json.dumps(cassette, indent=2, sort_keys=False) + "\n", encoding="utf-8"
    )
    return cassette


