def record_traces(
    scenarios: Sequence[Scenario],
    corpus: Corpus,
    *,
    root: Path,
    showcase: str,
    write: bool = True,
) -> dict[str, Trace]:
    """Replay every scenario from the committed fixtures and return the traces.

    This is the function `tests/test_audio_replay.py` calls to verify the
    committed traces, which is why it takes `write=False`: the test runs the exact
    generator the fixtures came from and compares, so a fixture that no longer
    matches the code is a failing test rather than a stale file nobody noticed.
    """
    fixture_tts = FixtureTTS(root)
    cassette = TranscriptCassette.load(root)
    traces: dict[str, Trace] = {}
    trace_dir = root / "traces"
    if write:
        trace_dir.mkdir(parents=True, exist_ok=True)
    for scenario in scenarios:
        assert scenario.voice is not None
        clock = FakeClock()
        adapter = AudioAdapter(
            tts=fixture_tts,
            stt=RecordedSTT(cassette),
            agent_tts=fixture_tts,
            sample_rate=scenario.voice.sample_rate,
            perturbations=scenario.voice.chain(),
            # The gate runs for real here: these traces are what the latency
            # figures in the case study are drawn from, and a trace recorded
            # with the gate skipped would refuse to produce them.
            gate=LatencyGate(),
            synthesise_agent_audio=scenario.id == showcase,
        )
        trace = adapter.run(
            scenario_id=scenario.id,
            agent=build_agent(clock=clock),
            caller=build_caller(scenario, corpus),
            clock=clock,
            session_id=f"audio-{scenario.id}",
        )
        traces[scenario.id] = trace
        if write:
            write_jsonl(trace, trace_dir / f"{scenario.id}.jsonl")
    return traces


