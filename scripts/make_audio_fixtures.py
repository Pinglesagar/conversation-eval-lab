def discover_lines(
    scenarios: Sequence[Scenario], corpus: Corpus, *, tts: Any, showcase: str
) -> tuple[list[str], list[str]]:
    """Run every scenario with a real engine to learn which lines exist.

    Returns `(caller_lines, agent_lines)`, de-duplicated and in first-seen order
    so the manifest is diffable between runs.
    """
    caller_lines: list[str] = []
    agent_lines: list[str] = []
    for scenario in scenarios:
        assert scenario.voice is not None
        caller_tts = RecordingTTS(tts, role="caller")
        agent_tts = RecordingTTS(tts, role="agent")
        clock = FakeClock()
        adapter = AudioAdapter(
            tts=caller_tts,
            stt=ReferenceSTT(caller_tts),
            agent_tts=agent_tts,
            sample_rate=scenario.voice.sample_rate,
            perturbations=scenario.voice.chain(),
            gate=LatencyGate.skipped(),  # pass A is discovery, not measurement
            synthesise_agent_audio=scenario.id == showcase,
        )
        adapter.run(
            scenario_id=scenario.id,
            agent=build_agent(clock=clock),
            caller=build_caller(scenario, corpus),
            clock=clock,
        )
        for line in caller_tts.spoken:
            if line not in caller_lines:
                caller_lines.append(line)
        for line in agent_tts.spoken:
            if line not in agent_lines and line not in caller_lines:
                agent_lines.append(line)
    return caller_lines, agent_lines


