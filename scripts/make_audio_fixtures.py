def _size_table(manifest: dict[str, Any]) -> tuple[int, int, int, float]:
    """Measured Opus total, equivalent WAV total, sample count and the ratio."""
    clips = manifest["clips"].values()
    opus = sum(int(c["bytes"]) for c in clips)
    samples = sum(int(c["samples"]) for c in clips)
    wav = sum(wav_bytes_for(int(c["samples"])) for c in clips)
    ratio = (wav / opus) if opus else 0.0
    return opus, wav, samples, ratio


def write_readme(
    root: Path,
    *,
    manifest: dict[str, Any],
    cassette: dict[str, Any],
    traces: dict[str, Trace],
    showcase: str,
    sample_rate: int,
) -> Path:
    """Write `audio_fixtures.md`: what is committed, where it came from, what it cost."""
    opus, wav, samples, ratio = _size_table(manifest)
    seconds = samples / sample_rate
    provenances = sorted({str(e.get("provenance")) for e in cassette["entries"].values()})
    lines: list[str] = [
        "# Committed audio fixtures",
        "",
        "Generated by `scripts/make_audio_fixtures.py` (`make audio-fixtures`). Every",
        "number below is measured by that script at generation time, not estimated.",
        "",
        f"- generated: {date.today().isoformat()}",
        f"- synthesiser: `{manifest['engine']}`"
        + (f" voice `{manifest['voice']}`" if manifest.get("voice") else ""),
        f"- format: {manifest['format']}",
        f"- transcript provenance: {', '.join(provenances)}",
        "",
        "## Size, and why nothing here is a WAV",
        "",
        "| | clips | audio | on disk |",
        "|---|---|---|---|",
        f"| Ogg Opus (committed) | {len(manifest['clips'])} | {seconds:.1f} s | "
        f"{opus / 1024:.1f} KiB |",
        f"| 16 kHz mono PCM16 WAV (not committed) | {len(manifest['clips'])} | "
        f"{seconds:.1f} s | {wav / 1024:.1f} KiB |",
        "",
        f"**{ratio:.1f}x smaller.** Git stores a binary blob per revision with no useful",
        "delta, so the WAV figure is not a one-off cost — it is that much added to the",
        "repository every time somebody regenerates.",
        "",
        "## What is committed, and what each tier proves",
        "",
        "| tier | contents | what it makes possible |",
        "|---|---|---|",
        f"| traces | `traces/*.jsonl`, {len(traces)} session(s) | every contract, latency"
        " figure and report row; consumed with no audio at all |",
        "| caller clips | one per caller line, every scenario | the perturbation chain,"
        " the digests, the STT leg and exact replay |",
        f"| agent clips | `{showcase}` only | `agent_audio_complete`, hence real speaking"
        " time |",
        "",
        "Agent audio is committed for one scenario rather than eight because the agent's",
        "replies are several times longer in total than the caller's lines, and their only",
        "unique contribution is speaking time. One session demonstrates the events and the",
        "arithmetic; eight would multiply the bytes for nothing new.",
        "",
        "## Sessions",
        "",
        "| scenario | turns | events | caller clips | agent audio |",
        "|---|---|---|---|---|",
    ]
    for scenario_id, trace in traces.items():
        callers = len(trace.events_of_kind("caller_utterance"))
        agent_audio = "yes" if trace.first("agent_audio_complete") is not None else "no"
        lines.append(
            f"| `{scenario_id}` | {callers} | {len(trace)} | {callers} | {agent_audio} |"
        )
    lines += [
        "",
        "## The transcripts are references, and the harness refuses to score them",
        "",
        "No speech-recognition engine is committed here and none is downloaded at test",
        "time, so each entry in `transcripts.json` is the line the caller actually spoke,",
        'labelled `provenance: "reference"`. Word error rate against the reference is',
        "exactly 0.0% by construction — on the clean rows and on the 6 dB-SNR-down-a-",
        "telephone-line row alike — so `lab.voice.adapter.audio_wer_report` refuses to",
        "compute it and says why.",
        "",
        "To get a real figure: `scripts/setup_audio.sh` installs whisper.cpp, then",
        "`python -m scripts.make_audio_fixtures --stt whisper` re-records the cassette",
        'with `provenance: "recorded"`, and the same call starts answering.',
        "",
        "## Regenerating is a no-op when the audio has not changed",
        "",
        "An Ogg bitstream carries a randomly chosen stream serial number, so encoding the",
        "same samples twice produces two files with identical audio and different bytes.",
        "Left alone that would add the whole clip set to git history on every run. The",
        "generator therefore compares *decoded* audio rather than bytes and leaves a",
        f"matching clip untouched — {manifest.get('clips_unchanged', 0)}/"
        f"{len(manifest['clips'])} clip(s) were reused on the run that produced this file.",
        "",
        "## Regenerating",
        "",
        "```",
        "make audio-fixtures                                    # macOS `say`, no download",
        "python -m scripts.make_audio_fixtures --engine kokoro   # local Kokoro-82M",
        "python -m scripts.make_audio_fixtures --check           # verify, write nothing",
        "```",
        "",
        "`tests/test_audio_replay.py` re-runs the final pass and compares against the",
        "committed traces, so a fixture that has drifted from the code is a failing test",
        "rather than a stale file.",
        "",
    ]
    path = root / "audio_fixtures.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


